import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {providerReadState}=await import('data:text/javascript,'+encodeURIComponent(readFileSync('web/provider-read.js','utf8')));
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
let hub='a';const state=()=>providerReadState(()=>hub,storage);
const m={src:'telegram',id:'tg:1',target:'a'},other={...m,target:'b'};
const s=state();assert.equal(s.supported({...m,target:null}),false);assert.equal(s.supported({...m,src:'dm'}),false);
const q=s.begin(m,'original');assert.deepEqual(state().begin(m,'new'),q);
for(const wrong of [{rid:'other'},{target:'other'},{id:'other'},{target:undefined}])assert.equal(s.accept({...q,kind:'read',...wrong}),false);
assert.equal(s.get(m).state,'pending');assert.equal(s.get(other),null);
hub='b';assert.equal(s.get(m),null);hub='a';
assert.equal(s.accept({...q,kind:'read'}),true);assert.equal(state().get(m).state,'read');assert.equal(s.begin(m,'new'),null);
s.accept({...q,kind:'read_failed',unresolved:true});assert.equal(s.get(m).state,'read');
const q2=s.begin(other,'second');s.accept({...q2,kind:'read_failed',unresolved:true,error:'Check source'});
assert.equal(s.get(other).state,'unknown');assert.equal(state().begin(other,'third'),null);
const third={...m,id:'tg:3'},q3=s.begin(third,'third');s.accept({...q3,kind:'read_failed',error:'Provider error'});
assert.equal(s.begin(third,'fourth'),null,'A provider exception cannot prove the external side effect did not happen');
const denied=providerReadState(()=>hub,{getItem:()=>null,setItem(){throw Error('quota')}});
assert.throws(()=>denied.begin(m,'denied'),/No request was sent/);
let writes=0;const corrupt=providerReadState(()=>hub,{getItem:()=>'{bad',setItem(){writes++}});
assert.equal(corrupt.get(m).state,'blocked');assert.throws(()=>corrupt.begin(m,'bad'));assert.equal(writes,0);
assert.throws(()=>s.begin({...m,id:'x'.repeat(256*1024)},'oversized'));
assert.equal(state().get(m).state,'read','Capacity refusal must preserve earlier receipts');
console.log('Provider reads retain original requests across reload, reject wrong receipts and refuse unsafe resends');

const populated=[];
for(let i=0;i<1500;i++)populated.push([JSON.stringify(['old-'+i+'x'.repeat(130),'a']),{rid:'old-'+i,state:'read'}]);
values.set('hub.inbox.provider-read.v1:a',JSON.stringify(populated));
const next=s.begin(m,'compact');assert.equal(next.rid,'compact');
assert.equal(s.accept({...next,kind:'read_failed',error:'x'.repeat(300000)}),true,'Reserved receipt space handles a bounded failure without losing the pending rid');
assert.equal(s.get(m).state,'failed');assert.ok(s.get(m).error.length<=240);
