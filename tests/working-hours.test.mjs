import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {workingHours,nextWorkingStart,workingStartLabel}=await import('data:text/javascript,'+encodeURIComponent(readFileSync('web/working-hours.js','utf8')));
const base={from:'08:00',to:'20:00',weekends:false,tz:'America/Argentina/Buenos_Aires',utc:-180,except:[]};
const next=(now,changes={},contact='a')=>nextWorkingStart(workingHours({...base,...changes}),contact,new Date(now))?.toISOString();
assert.equal(next('2026-10-16T10:59:00Z'),'2026-10-16T11:00:00.000Z');
assert.equal(next('2026-10-16T11:00:00Z'),'2026-10-19T11:00:00.000Z');
assert.equal(next('2026-10-17T12:00:00Z'),'2026-10-19T11:00:00.000Z');
assert.equal(next('2026-10-16T12:00:00Z',{except:[{contact:'a'}]}),'2026-10-17T11:00:00.000Z');
assert.equal(next('2026-10-16T12:00:00Z',{weekends:true,except:[{contact:'a'}]}),'2026-10-19T11:00:00.000Z');
assert.equal(next('2026-10-16T12:00:00Z',{from:'09:30'}),'2026-10-16T12:30:00.000Z');
assert.equal(next('2026-03-07T15:00:00Z',{tz:'America/New_York',weekends:true}),'2026-03-08T12:00:00.000Z');
assert.equal(next('2026-10-31T15:00:00Z',{tz:'America/New_York',weekends:true}),'2026-11-01T13:00:00.000Z');
assert.equal(next('2026-03-08T06:00:00Z',{tz:'America/New_York',from:'02:30',weekends:true}),'2026-03-08T07:30:00.000Z');
assert.equal(next('2026-11-01T06:15:00Z',{tz:'America/New_York',from:'01:30',weekends:true}),'2026-11-01T06:30:00.000Z');
assert.equal(next('2026-10-16T01:00:00Z',{tz:'invalid',utc:330}),'2026-10-16T02:30:00.000Z');
for(const bad of [null,{}, {...base,from:'25:00'}, {...base,to:'07:00'}, {...base,tz:'invalid',utc:null}])assert.equal(workingHours(bad),null);
assert.equal(nextWorkingStart(null,'a',new Date()),null);
assert.match(workingStartLabel(new Date('2026-10-19T11:00:00Z'),new Date('2026-10-16T12:00:00Z'),'Asia/Tokyo'),/Monday.*20:00/);
console.log('Working start: exact contact, strict future, Hub timezone/DST, offset fallback and device label passed');
