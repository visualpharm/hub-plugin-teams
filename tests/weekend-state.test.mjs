import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {recipientWeekendState}=await import('data:text/javascript,'+encodeURIComponent(readFileSync('web/working-hours.js','utf8')));
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
let hub='a';const state=()=>recipientWeekendState(()=>hub,storage);
const m={src:'telegram',id:'a',contact:'person',target:'target-a'},s=state();
const q=s.begin(m,true,'original');assert.deepEqual(state().begin(m,false,'new'),q);
for(const wrong of [{rid:'wrong'},{target:'wrong'},{contact:'wrong'},{id:'wrong'},{target:undefined},{requested:false}])assert.equal(s.accept({...q,kind:'hours_set',requested:true,...wrong},m),false);
assert.equal(s.get(m).state,'pending');
assert.equal(s.get({...m,target:'b'}).q.rid,q.rid,'Pending settings belong to the contact across message replacement');hub='b';assert.equal(s.get(m),null);hub='a';
assert.equal(s.accept({...q,kind:'hours_set',requested:true},m),true);assert.equal(s.get(m).state,'ok');
assert.equal(s.accept({...q,kind:'hours_failed',error:'Late failure'},m),false);
const next=s.begin(m,false,'next');assert.equal(next.weekends,false);assert.equal(next.rid,'next');
s.accept({...next,kind:'hours_failed',error:'Refused'},m);assert.equal(s.get(m).state,'failed');
const retry=s.begin(m,false,'retry');s.accept({...retry,kind:'hours_failed',unresolved:true},m);
assert.equal(s.get(m).state,'unknown');assert.deepEqual(s.begin(m,true,'unsafe'),retry);assert.equal(s.accept({...retry,kind:'hours_set',requested:false,weekends:false},{...m,target:'rebound'}),true);assert.equal(s.get(m).state,'ok');
const denied=recipientWeekendState(()=>hub,{getItem:()=>null,setItem(){throw Error('quota')}});
assert.throws(()=>denied.begin(m,true,'no'),/No change was sent/);
const corrupt=recipientWeekendState(()=>hub,{getItem:()=>'{broken',setItem(){throw Error('must not overwrite')}});
assert.equal(corrupt.get(m).state,'blocked');assert.throws(()=>corrupt.begin(m,true,'no'));
console.log('Weekend setting requests survive reload, reject mismatched receipts, and retain unknown outcomes');
